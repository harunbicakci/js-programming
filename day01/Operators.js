// Arithmetic Operators

console.log(20 + 10);
console.log(20 - 5);
console.log(20 * 10);
console.log(20 / 10);

console.log("--------------------------------");

let x;
x = 200;
console.log(x);

x += 100;
console.log(x);

x -= 50;
console.log(x);
console.log("--------------------------------");

console.log(100 > 200);
console.log(10 >= 10);
console.log(100 == "100"); // Equal: ignores the data type

console.log(100 === "100"); // Strict equal: does not ignore the data type
console.log(100 != "100"); // Not equal: ignores the data type
console.log(100 !== "100"); // Strict Not equal: ignores the data type
console.log("--------------------------------");

console.log(true && true);
console.log(true && false);
console.log(true || false);
console.log(false|| false);

console.log(!true);